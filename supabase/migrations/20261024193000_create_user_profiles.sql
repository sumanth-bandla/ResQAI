create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  public_user_id text not null unique,
  full_name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_full_name_length check (char_length(btrim(full_name, E' \t\n\r\f')) between 1 and 100),
  constraint profiles_public_user_id_format check (public_user_id ~ '^RSQ-[A-F0-9]{8}$')
);

create index if not exists profiles_created_at_idx on public.profiles (created_at desc);

alter table public.profiles enable row level security;

revoke all on table public.profiles from anon, authenticated;
grant select on table public.profiles to authenticated;
grant update (full_name) on table public.profiles to authenticated;
grant all on table public.profiles to service_role;

drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile"
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles
  for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  generated_user_id text;
  normalized_full_name text;
  attempt integer := 0;
begin
  normalized_full_name := btrim(coalesce(new.raw_user_meta_data ->> 'full_name', ''), E' \t\n\r\f');
  if char_length(normalized_full_name) not between 1 and 100 then
    raise exception 'A valid full name is required to create a profile';
  end if;

  loop
    attempt := attempt + 1;
    generated_user_id := 'RSQ-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 8));
    insert into public.profiles (id, public_user_id, full_name)
    values (new.id, generated_user_id, normalized_full_name)
    on conflict (public_user_id) do nothing;

    if found then
      return new;
    end if;

    if attempt >= 10 then
      raise exception 'Unable to generate a unique public user ID';
    end if;
  end loop;
end;
$$;

revoke all on function public.handle_new_user_profile() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute function public.handle_new_user_profile();

create or replace function public.update_profile_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  return new;
end;
$$;

revoke all on function public.update_profile_updated_at() from public, anon, authenticated;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.update_profile_updated_at();

do $$
declare
  existing_user record;
  generated_user_id text;
  normalized_full_name text;
  attempt integer;
begin
  for existing_user in
    select users.id, users.raw_user_meta_data
    from auth.users as users
    left join public.profiles as profiles on profiles.id = users.id
    where profiles.id is null
  loop
    normalized_full_name := btrim(coalesce(existing_user.raw_user_meta_data ->> 'full_name', ''), E' \t\n\r\f');
    if char_length(normalized_full_name) not between 1 and 100 then
      normalized_full_name := 'ResQAI User';
    end if;

    attempt := 0;
    loop
      attempt := attempt + 1;
      generated_user_id := 'RSQ-' || upper(substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 8));
      insert into public.profiles (id, public_user_id, full_name)
      values (existing_user.id, generated_user_id, normalized_full_name)
      on conflict (public_user_id) do nothing;

      exit when found;
      if attempt >= 10 then
        raise exception 'Unable to generate a unique public user ID for an existing account';
      end if;
    end loop;
  end loop;
end;
$$;

comment on table public.profiles is
  'Self-service account profile. The Auth UUID and public_user_id are immutable to browser clients.';
comment on column public.profiles.public_user_id is
  'Unique display identifier generated by a trusted database trigger; not an authentication credential.';
